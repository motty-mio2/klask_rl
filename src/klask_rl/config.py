# Configuration file for Klask RL Environment

# カメラの都合による推論周期 (Hz)
INFERENCE_HZ = 30.0

# 1回の推論（環境の1ステップ）あたりの MuJoCo 物理演算サブステップ数。
# 物理演算を安定させるために、通常 0.001s 〜 0.003s 程度のタイムステップが推奨されます。
# 30Hz (1ステップ 0.03333...秒) を正確に表現するため、
# シミュレータの物理タイムステップは `(1.0 / INFERENCE_HZ) / MUJOCO_SUBSTEPS` に自動設定されます。
# 例: 16サブステップに設定すると、1つの物理タイムステップは約 0.002083 秒となり、物理的にも非常に安定します。
MUJOCO_SUBSTEPS = 16

# モータスペック (CoreXY)
# 1回転 = 400ステップ (GT2 20歯プーリにより 1歩 = 0.1mm = 0.0001m 換算)
MOTOR_STEP_TO_M = 0.0001
MOTOR_MAX_VELOCITY = 0.2  # 2000 step/s * 0.0001m = 0.2 m/s
MOTOR_MAX_ACCEL = 0.2     # 2000 step/s^2 * 0.0001m = 0.2 m/s^2

# 過去の履歴を何枚残すか (現在含むフレームスタック数)
# 速度 (1階差分) と加速度 (2階差分) を捉えるためには、現在 + 過去2フレーム = 計3フレーム が適切です。
NUM_HISTORY_FRAMES = 3

# ==========================================
# ドメインランダマイゼーション (Domain Randomization)
# ==========================================
ENABLE_DR = True  # ドメインランダマイゼーションを有効にするか

# 各物理パラメータのランダマイズ範囲 (最小値, Max値)
DR_PUCK_FRICTION = (0.02, 0.10)     # パックの摩擦係数 (デフォルト: 0.05)
DR_STRIKER_FRICTION = (0.05, 0.20)   # ストライカーの摩擦係数 (デフォルト: 0.1)
DR_PUCK_MASS = (0.003, 0.008)       # パックの質量 kg (デフォルト: 0.005)
DR_STRIKER_MASS = (0.08, 0.12)      # ストライカーの質量 kg (デフォルト: 0.1)

# モータ制限のランダマイズ範囲 (最高速度, 最高加速度)
DR_MOTOR_MAX_VELOCITY = (0.16, 0.24) # モータ最高速度 m/s (デフォルト: 0.2)
DR_MOTOR_MAX_ACCEL = (0.16, 0.24)    # モータ最高加速度 m/s^2 (デフォルト: 0.2)

# 制御入力遅延のランダマイズ範囲 (最小ステップ数, 最大ステップ数)
# 30Hz時、1ステップ = 33.3ms。 (0, 2) の場合、各エピソードで 0ms、33.3ms、66.6ms のいずれかの遅延が設定されます
DR_CONTROL_LATENCY = (0, 2)

# ==========================================
# チェックポイント保存設定
# ==========================================
SAVE_CHECKPOINT_STEPS = 100000  # 何環境ステップごとにモデルのチェックポイントを保存するか

# ==========================================
# 報酬・ペナルティ調整設定
# ==========================================
# ボールが自陣 (y < 0) にある時のステップあたりペナルティ係数
# y座標の深さに比例してペナルティが与えられます (例: 10.0 のとき、y=-0.15なら毎ステップ -1.5点)
PENALTY_PUCK_IN_OWN_HALF = 10.0



